#!/usr/bin/env python3
"""Инженерный расчёт варианта 13: мощность и тепловыделение серверного оборудования.

Считается оборудование, на котором разворачивается система поддержки выбора
поставщика: сервер приложений, сервер базы данных, сервер резервных копий
и сетевое оборудование. Результат — потребляемая мощность, тепловыделение,
подбор ИБП и кондиционера, годовое потребление.

Все числа отчёта берутся из вывода этого скрипта.

    python3 power.py
"""
from __future__ import annotations

import math
from pathlib import Path

HERE = Path(__file__).resolve().parent

# Исходные данные: оборудование, номинальная мощность блока питания и средний
# коэффициент загрузки. Загрузка взята средняя за сутки, а не пиковая.
ОБОРУДОВАНИЕ = [
    ("Сервер приложений",            500, 0.55),
    ("Сервер базы данных",           750, 0.65),
    ("Сервер резервного копирования", 400, 0.45),
    ("Коммутатор доступа",            60, 0.80),
    ("Маршрутизатор с межсетевым экраном", 40, 0.70),
]

КПД_ИБП = 0.92        # КПД источника бесперебойного питания в линейном режиме
COS_FI = 0.95         # коэффициент мощности блоков питания с активным ККМ
ЗАПАС_ИБП = 1.30      # запас по полной мощности при подборе ИБП
ЗАПАС_ХОЛОДА = 1.20   # запас по холодопроизводительности кондиционера
ВТ_В_БТЕ = 3.412      # 1 Вт = 3,412 БТЕ/ч
PUE = 1.70            # отношение полного потребления объекта к потреблению ИТ
ЧАСОВ_В_ГОДУ = 8760
ТАРИФ = 6.50          # руб. за кВт*ч

# Батарея ИБП: две батареи 12 В по 9 А*ч, КПД инвертора и глубина разряда
БАТАРЕЯ_В = 24
БАТАРЕЯ_АЧ = 9
КПД_ИНВЕРТОРА = 0.90
ГЛУБИНА_РАЗРЯДА = 0.80


def main() -> None:
    строки = ["ИНЖЕНЕРНЫЙ РАСЧЁТ. Мощность и тепловыделение серверного оборудования",
              "", "Исходные данные:",
              f"{'Оборудование':<38} {'Pном, Вт':>9} {'Загрузка':>9} {'Pср, Вт':>9}"]
    итог = 0.0
    for имя, номинал, загрузка in ОБОРУДОВАНИЕ:
        сред = номинал * загрузка
        итог += сред
        строки.append(f"{имя:<38} {номинал:>9} {загрузка:>9.2f} {сред:>9.1f}")
    строки.append(f"{'Итого потребление ИТ-оборудования':<38} {'':>9} {'':>9} {итог:>9.1f}")

    # 1. Мощность на входе ИБП: к нагрузке добавляются его собственные потери
    вход = итог / КПД_ИБП
    потери = вход - итог

    # 2. Полная мощность и подбор ИБП
    полная = вход / COS_FI
    ибп = полная * ЗАПАС_ИБП

    # 3. Тепловыделение: вся потреблённая в стойке мощность переходит в тепло
    тепло_вт = вход
    тепло_бте = тепло_вт * ВТ_В_БТЕ
    холод = тепло_вт * ЗАПАС_ХОЛОДА

    # 4. Автономия ИБП
    энергия = БАТАРЕЯ_В * БАТАРЕЯ_АЧ
    полезная = энергия * КПД_ИНВЕРТОРА * ГЛУБИНА_РАЗРЯДА
    автономия_мин = полезная / итог * 60

    # 5. Годовое потребление с учётом охлаждения и прочей нагрузки
    полное = итог * PUE
    год_квтч = полное * ЧАСОВ_В_ГОДУ / 1000
    год_руб = год_квтч * ТАРИФ

    строки += [
        "", "Результаты:",
        f"  Потребление ИТ-оборудования P_ит           = {итог:.1f} Вт",
        f"  Мощность на входе ИБП (КПД {КПД_ИБП})         = {вход:.1f} Вт",
        f"  Собственные потери ИБП                     = {потери:.1f} Вт",
        f"  Полная мощность S (cos f = {COS_FI})           = {полная:.1f} В*А",
        f"  Требуемая мощность ИБП с запасом {ЗАПАС_ИБП}    = {ибп:.1f} В*А"
        f"  -> типоразмер 2000 В*А",
        f"  Тепловыделение Q                           = {тепло_вт:.1f} Вт"
        f" = {тепло_вт / 1000:.3f} кВт = {тепло_бте:.0f} БТЕ/ч",
        f"  Холодопроизводительность с запасом {ЗАПАС_ХОЛОДА}   = {холод:.1f} Вт"
        f"  -> сплит-система 1,5 кВт",
        f"  Автономия ИБП при батарее {БАТАРЕЯ_В} В {БАТАРЕЯ_АЧ} А*ч     ="
        f" {автономия_мин:.1f} мин",
        f"  Полное потребление объекта (PUE {PUE})      = {полное:.1f} Вт",
        f"  Потребление за год                         = {год_квтч:.0f} кВт*ч",
        f"  Стоимость электроэнергии за год            = {год_руб:.0f} руб.",
    ]

    строки += [
        "", "Проверки:",
        f"  тепло равно мощности на входе ИБП: {abs(тепло_вт - вход) < 1e-9}",
        f"  доля серверов в потреблении ИТ: "
        f"{100 * sum(н * з for и, н, з in ОБОРУДОВАНИЕ[:3]) / итог:.1f} %",
        f"  запас ИБП над полной мощностью: {2000 / полная:.2f} раза",
        f"  сплит-система 1,5 кВт покрывает нагрузку: {1500 >= холод}",
    ]

    # Вариант проектного этапа: компонент работает на сервере базы данных.
    # Замер показал расчёт за доли секунды, отдельный сервер приложений
    # нужен не для мощности; сервер копий остаётся ради надёжности.
    без_приложений = итог - ОБОРУДОВАНИЕ[0][1] * ОБОРУДОВАНИЕ[0][2]
    вход2 = без_приложений / КПД_ИБП
    год2 = без_приложений * PUE * ЧАСОВ_В_ГОДУ / 1000
    строки += [
        "", "Вариант без отдельного сервера приложений:",
        f"  Потребление ИТ-оборудования                = {без_приложений:.1f} Вт",
        f"  Тепловыделение                             = {вход2:.1f} Вт",
        f"  Потребление за год                         = {год2:.0f} кВт*ч",
        f"  Экономия за год                            = {год_квтч - год2:.0f} кВт*ч"
        f" = {(год_квтч - год2) * ТАРИФ:.0f} руб.",
    ]

    текст = "\n".join(строки)
    print(текст)
    (HERE / "power.log").write_text(текст + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
