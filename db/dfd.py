def раскладка() -> dict[str, tuple[ч.Блок, str]]:
    верх_ряда, y = [], 2.0
    for h in ВЫСОТА_РЯДА:
        верх_ряда.append(y)
        y += h + ЗАЗОР
    фигуры: dict[str, tuple[ч.Блок, str]] = {}

    def поставить(ид, вид, столбец, ряд, высота):
        x = 1.0 + столбец * (ШИРИНА + ПРОМЕЖУТОК)
        центр = верх_ряда[ряд] + ВЫСОТА_РЯДА[ряд] / 2
        фигуры[ид] = (ч.Блок(x, центр - высота / 2, ШИРИНА, высота), вид)

    for ид, _, с, р in ВНЕШНИЕ:
        поставить(ид, "внешняя", с, р, 10.0)
    for ид, _, _, с, р in ПРОЦЕССЫ:
        поставить(ид, "процесс", с, р, 17.5)
    for ид, _, _, с, р in ХРАНИЛИЩА:
        поставить(ид, "хранилище", с, р, 10.0)
    return фигуры


def нарисовать_фигуры(х: ч.Холст, фигуры) -> None:
    for ид, имя, *_ in ВНЕШНИЕ:
        б, _ = фигуры[ид]
        х.прямоугольник(б.x, б.y, б.w, б.h, "#fdebd0", толщина=0.9)
        х.текст(б.x + б.w / 2, б.y + б.h / 2, имя, КЕГЛЬ, ha="center")
    for ид, номер, имя, *_ in ПРОЦЕССЫ:
        б, _ = фигуры[ид]
        х.прямоугольник(б.x, б.y, б.w, б.h, "#dbe5f1", скругление=2.2, толщина=0.9)
        х.линия([(б.x, б.y + 4.6), (б.право, б.y + 4.6)], 0.6)
        х.текст(б.x + б.w / 2, б.y + 2.4, номер, КЕГЛЬ, True, ha="center")
        х.текст(б.x + б.w / 2, б.y + 4.6 + (б.h - 4.6) / 2, имя, КЕГЛЬ, ha="center")
    for ид, код, имя, *_ in ХРАНИЛИЩА:
        б, _ = фигуры[ид]
        х.прямоугольник(б.x, б.y, 7.0, б.h, "#e8e8e8", контур=False)
        х.прямоугольник(б.x + 7.0, б.y, б.w - 7.0, б.h, "white", контур=False)
        х.линия([(б.право, б.y), (б.x, б.y), (б.x, б.низ), (б.право, б.низ)], 0.9)
        х.линия([(б.x + 7.0, б.y), (б.x + 7.0, б.низ)], 0.6)
        х.текст(б.x + 3.5, б.y + б.h / 2, код, КЕГЛЬ, ha="center")
        х.текст(б.x + 7.0 + 1.8, б.y + б.h / 2, имя, КЕГЛЬ, ha="left")


def подпись(х: ч.Холст, точки, где: str, текст: str) -> None:
    """Подпись у самого длинного отрезка нужного направления."""
    отрезки = list(zip(точки, точки[1:]))
    гор = где in ("над", "под")
    подходящие = [(a, b) for a, b in отрезки if (abs(a[1] - b[1]) < 1e-6) == гор]
    (xa, ya), (xb, yb) = max(подходящие, key=lambda o: abs(o[0][0] - o[1][0]) + abs(o[0][1] - o[1][1]))
    if гор:
        x = (xa + xb) / 2
        if где == "над":
            х.текст(x, ya - 0.9, текст, КЕГЛЬ_ПОТОКА, ha="center", va="bottom", фон="white")
        else:
            х.текст(x, ya + 0.9, текст, КЕГЛЬ_ПОТОКА, ha="center", va="top", фон="white")
    else:
        y = (ya + yb) / 2
        if где == "справа":
            х.текст(xa + 1.2, y, текст, КЕГЛЬ_ПОТОКА, ha="left", фон="white")
        else:
            х.текст(xa - 1.2, y, текст, КЕГЛЬ_ПОТОКА, ha="right", фон="white")


def main() -> int:
    фигуры = раскладка()
    ширина = max(б.право for б, _ in фигуры.values()) + 1.0
    высота = max(б.низ for б, _ in фигуры.values()) + 5.0
    х = ч.Холст(ширина, высота)
    нарисовать_фигуры(х, фигуры)
    for откуда, сa, да, куда, сb, дb, текст, где in ПОТОКИ:
        a = фигуры[откуда][0].точка(сa, да)
        b = фигуры[куда][0].точка(сb, дb)
        точки = ч.путь(a, сa, b, сb)
        х.стрелка(точки, 0.8)
        подпись(х, точки, где, текст)
    х.сохранить(IMG / "dfd")
    # потоки без подписи и висящие элементы — ошибка диаграммы
    концы = {п[0] for п in ПОТОКИ} | {п[3] for п in ПОТОКИ}
    висящие = set(фигуры) - концы
    assert not висящие, f"элементы без потоков: {висящие}"
    assert all(п[6].strip() for п in ПОТОКИ), "поток без подписи"
    print(f"dfd: {ширина:.0f} x {высота:.0f} мм; внешних сущностей {len(ВНЕШНИЕ)}, "
          f"процессов {len(ПРОЦЕССЫ)}, хранилищ {len(ХРАНИЛИЩА)}, потоков {len(ПОТОКИ)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
