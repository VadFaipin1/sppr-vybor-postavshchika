"""Диаграмма потоков данных нулевого уровня (нотация Гейна-Сарсона).

Внешние сущности — прямоугольники, процессы — прямоугольники со скруглением
и номером, хранилища — открытые справа прямоугольники с кодом D1…D5.

Раскладка ручная, по сетке из пяти столбцов и шести рядов: каждый поток
идёт прямой линией или с одним изломом, потоки не пересекаются, подпись
стоит у своей линии. Рисуется в натуральную величину альбомного листа.

    python3 dfd.py          # пишет ../img/dfd.png и ../img/dfd.svg
"""
