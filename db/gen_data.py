def инн(rnd: random.Random) -> str:
    return "".join(str(rnd.randint(0, 9)) for _ in range(10))


def кв(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def main() -> None:
    rnd = random.Random(SEED)
    out: list[str] = ["SET search_path TO zakupki;", ""]

    out.append("INSERT INTO tovarnaya_gruppa (id, naimenovanie) VALUES")
    out.append(",\n".join(f"  ({i}, {кв(n)})" for i, n in ГРУППЫ) + ";\n")

    out.append("INSERT INTO tovar (id, naimenovanie, gruppa_id, edinica,"
               " kratnost_upakovki, srok_godnosti_dney) VALUES")
    строки = []
    for i, (гр, имя, ед, кратн, срок, *_) in enumerate(ТОВАРЫ, 1):
        строки.append(f"  ({i}, {кв(имя)}, {гр}, {кв(ед)}, {кратн}, "
                      f"{срок if срок else 'NULL'})")
    out.append(",\n".join(строки) + ";\n")

    out.append("INSERT INTO postavshchik (id, naimenovanie, inn, otsrochka_dney,"
               " min_summa_zakaza) VALUES")
    строки = []
    for i, (имя, отср, мин, *_) in enumerate(ПОСТАВЩИКИ, 1):
        строки.append(f"  ({i}, {кв(имя)}, '{инн(rnd)}', {отср}, {мин})")
    out.append(",\n".join(строки) + ";\n")

    out.append("INSERT INTO klient (id, naimenovanie, inn) VALUES")
    out.append(",\n".join(f"  ({i}, {кв(имя)}, '{инн(rnd)}')"
                          for i, имя in enumerate(КЛИЕНТЫ, 1)) + ";\n")

    # каждый товар есть у 2-4 поставщиков; цена и срок пляшут вокруг базовых
    прайс, прайс_id = [], 0
    поставщики_товара: dict[int, list[int]] = {}
    for т, (гр, имя, ед, кратн, срок, база, *_) in enumerate(ТОВАРЫ, 1):
        кандидаты = rnd.sample(range(1, len(ПОСТАВЩИКИ) + 1), rnd.randint(2, 4))
        поставщики_товара[т] = кандидаты
        for п in кандидаты:
            _, _, _, множ, срок_п, _ = ПОСТАВЩИКИ[п - 1]
            цена = round(база * множ * rnd.uniform(0.95, 1.06), 2)
            дней = max(2, round(срок_п * rnd.uniform(0.8, 1.25)))
            прайс_id += 1
            прайс.append((прайс_id, п, т, цена, дней))
    out.append("INSERT INTO prays (id, postavshchik_id, tovar_id, cena,"
               " srok_postavki_dney, deystvuet_s) VALUES")
    out.append(",\n".join(f"  ({i}, {п}, {т}, {ц}, {д}, '2025-11-01')"
                          for i, п, т, ц, д in прайс) + ";\n")

    # Спрос задаётся по товару и дню: медиана равна спросу из справочника,
    # разброс — его же коэффициент вариации. Дневной спрос делится между
    # одной-тремя заявками случайных клиентов. Так недельная вариация у товара
    # остаётся его собственной, и ABC с XYZ дают разные классы, а не один.
    otg_id = zay_id = sz_id = so_id = 0
    зая, стр_зая, отг, стр_отг = [], [], [], []
    д = НАЧАЛО
    while д <= КОНЕЦ:
        if д.weekday() < 6:
            корзины: dict[int, list[tuple[int, int]]] = {}
            for т, (гр, имя, ед, кратн, срок, база, спрос, разброс) in enumerate(ТОВАРЫ, 1):
                мю = math.log(спрос)
                за_день = round(rnd.lognormvariate(мю, разброс))
                if за_день <= 0:
                    continue
                части = rnd.randint(1, 3)
                клиенты = rnd.sample(range(1, len(КЛИЕНТЫ) + 1), части)
                доли = [rnd.random() for _ in range(части)]
                сумма = sum(доли)
                роздано = 0
                for к, доля in zip(клиенты, доли):
                    кол = round(за_день * доля / сумма)
                    роздано += кол
                    if кол > 0:
                        корзины.setdefault(к, []).append((т, кол))
                if роздано == 0:
                    корзины.setdefault(клиенты[0], []).append((т, за_день))
            for клиент, позиции in корзины.items():
                zay_id += 1
                otg_id += 1
                зая.append((zay_id, клиент, д))
                отг.append((otg_id, zay_id, д))
                for т, кол in позиции:
                    база = ТОВАРЫ[т - 1][5]
                    sz_id += 1
                    so_id += 1
                    стр_зая.append((sz_id, zay_id, т, кол))
                    стр_отг.append((so_id, otg_id, т, кол,
                                    round(база * rnd.uniform(1.18, 1.34), 2)))
        д += timedelta(days=1)

    out.append("INSERT INTO zayavka (id, klient_id, data, status) VALUES")
    out.append(",\n".join(f"  ({i}, {к}, '{д}', 'отгружена')" for i, к, д in зая) + ";\n")
    out.append("INSERT INTO stroka_zayavki (id, zayavka_id, tovar_id, kolichestvo) VALUES")
    out.append(",\n".join(f"  ({i}, {з}, {т}, {к})" for i, з, т, к in стр_зая) + ";\n")
    out.append("INSERT INTO otgruzka (id, zayavka_id, data, nomer_upd) VALUES")
    out.append(",\n".join(f"  ({i}, {з}, '{д}', 'УПД-{i:05d}')" for i, з, д in отг) + ";\n")
    out.append("INSERT INTO stroka_otgruzki (id, otgruzka_id, tovar_id,"
               " kolichestvo, cena) VALUES")
    out.append(",\n".join(f"  ({i}, {о}, {т}, {к}, {ц})"
                          for i, о, т, к, ц in стр_отг) + ";\n")

    # закупки: каждому поставщику примерно раз в две недели
    зак_id = sz2_id = пост_id = sp_id = 0
    зак, стр_зак, пост, стр_пост = [], [], [], []
    срок_прайса = {(п, т): д for _, п, т, _, д in прайс}
    цена_прайса = {(п, т): ц for _, п, т, ц, _ in прайс}
    for п in range(1, len(ПОСТАВЩИКИ) + 1):
        _, _, _, _, _, дисциплина = ПОСТАВЩИКИ[п - 1]
        товары_п = [т for т, сп in поставщики_товара.items() if п in сп]
        if not товары_п:
            continue
        д = НАЧАЛО + timedelta(days=rnd.randint(0, 13))
        while д <= КОНЕЦ - timedelta(days=25):
            зак_id += 1
            срок = max(срок_прайса[(п, т)] for т in товары_п[:1]) if товары_п else 7
            срок = срок_прайса[(п, rnd.choice(товары_п))]
            план = д + timedelta(days=срок)
            зак.append((зак_id, п, д, план))
            позиции = rnd.sample(товары_п, min(len(товары_п), rnd.randint(2, 6)))
            пост_id += 1
            # дисциплина поставщика: опоздание и недопоставка
            в_срок = rnd.random() < дисциплина
            факт = план if в_срок else план + timedelta(days=rnd.randint(1, 9))
            if факт > КОНЕЦ:
                факт = КОНЕЦ
            пост.append((пост_id, зак_id, факт))
            for т in позиции:
                гр, имя, ед, кратн, срок_г, база, спрос, разброс = ТОВАРЫ[т - 1]
                кол = max(кратн, round(спрос * rnd.uniform(9, 20) / кратн) * кратн)
                sz2_id += 1
                стр_зак.append((sz2_id, зак_id, т, кол, цена_прайса[(п, т)]))
                недо = 0.0 if rnd.random() < дисциплина else rnd.uniform(0.03, 0.18)
                принято = round(кол * (1 - недо))
                брак = round(принято * rnd.uniform(0, 0.015))
                sp_id += 1
                стр_пост.append((sp_id, пост_id, т, принято, брак))
            д += timedelta(days=rnd.randint(11, 18))

    out.append("INSERT INTO zakaz_postavshchiku (id, postavshchik_id, data_zakaza,"
               " plan_data_postavki, status) VALUES")
    out.append(",\n".join(f"  ({i}, {п}, '{д}', '{пл}', 'принят')"
                          for i, п, д, пл in зак) + ";\n")
    out.append("INSERT INTO stroka_zakaza (id, zakaz_id, tovar_id, kolichestvo, cena) VALUES")
    out.append(",\n".join(f"  ({i}, {з}, {т}, {к}, {ц})"
                          for i, з, т, к, ц in стр_зак) + ";\n")
    out.append("INSERT INTO postavka (id, zakaz_id, fakt_data, nomer_dokumenta) VALUES")
    out.append(",\n".join(f"  ({i}, {з}, '{д}', 'ТН-{i:05d}')"
                          for i, з, д in пост) + ";\n")
    out.append("INSERT INTO stroka_postavki (id, postavka_id, tovar_id, prinyato, brak) VALUES")
    out.append(",\n".join(f"  ({i}, {п}, {т}, {пр}, {бр})"
                          for i, п, т, пр, бр in стр_пост) + ";\n")

    # Остатки на конец периода: покрытие в днях спроса. Разброс подобран так,
    # чтобы часть позиций оказалась ниже точки перезаказа, а часть — с запасом.
    ПОКРЫТИЕ = [1, 2, 3, 4, 5, 7, 9, 11, 14, 17, 20, 24, 28, 33, 38, 44]
    строки = []
    for т, (гр, имя, ед, кратн, срок, база, спрос, разброс) in enumerate(ТОВАРЫ, 1):
        дней = ПОКРЫТИЕ[(т * 7) % len(ПОКРЫТИЕ)]
        кол = round(спрос * дней * rnd.uniform(0.9, 1.1))
        строки.append(f"  ({т}, {кол}, {round(кол * rnd.uniform(0, 0.2))})")
    out.append("INSERT INTO ostatok (tovar_id, kolichestvo, rezerv) VALUES")
    out.append(",\n".join(строки) + ";")

    (HERE / "02_data.sql").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"02_data.sql: товаров {len(ТОВАРЫ)}, поставщиков {len(ПОСТАВЩИКИ)}, "
          f"клиентов {len(КЛИЕНТЫ)}, прайс-позиций {len(прайс)}")
    print(f"  отгрузок {len(отг)}, строк отгрузки {len(стр_отг)}")
    print(f"  заказов {len(зак)}, строк заказа {len(стр_зак)}, поставок {len(пост)}")


if __name__ == "__main__":
    main()
