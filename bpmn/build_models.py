#!/usr/bin/env python3
"""Модели BPMN к отчёту по учебной практике, вариант 13.

AS-IS, текущее состояние процесса «Закупка, приём и оптовая реализация товаров»:
потребность считается по остатку в выгрузке, поставщик выбирается по цене.

Две схемы. Основная показывает процесс целиком, подбор поставщика свёрнут в
подпроцесс. Декомпозиция раскрывает этот подпроцесс — именно в нём лежат
операции, которые тема работы предлагает автоматизировать.
Одной схемой это не делается: в один ряд получается 1890 px, текст задач
садится до 5 пт при предельной ширине рисунка 250 мм.

Пишет .bpmn, рисунки в ../img и сводку в ../run.log.

    python3 build_models.py
"""
from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ИНСТРУМЕНТ = HERE.parent.parent.parent / "БИЗНЕС ПРОЦЕССЫ" / "Инструменты" / "bpmn"
sys.path.insert(0, str(ИНСТРУМЕНТ))
from bpmn import Модель                                                      # noqa: E402

ШРИФТ = 13
ЗАДАЧА = (115, 95)        # три строки названия не задевают значок типа задачи
ПРОЦЕСС = "Закупка, приём и оптовая реализация товаров"
ПОДБОР = "Сформировать заказ поставщику"


def письмо(м: Модель, a, b, имя: str, y: float, x: float | None = None,
           слева: bool = False) -> None:
    """Поток сообщений с подписью в промежутке между пулами.

    Линия сообщения идёт через весь лист, и подпись у её середины легла бы
    на дорожки процесса. y — абсолютная координата середины промежутка."""
    w, h = м._размер_метки(имя)
    ниже = b.y > a.y
    y1 = a.y + a.h if ниже else a.y
    y2 = b.y if ниже else b.y + b.h
    м.сообщение(a, b, имя, x=x,
                подпись=(-6 - w if слева else 6, y - h / 2 - (y1 + y2) / 2))


def as_is() -> Модель:
    """Основная схема AS-IS: от расчёта потребности до отгрузки клиенту."""
    м = Модель("as_is", ЗАДАЧА, ШРИФТ)
    ш = 1300
    пул = м.пул(ПРОЦЕСС, 0, 0, ш, [
        ("Менеджер по закупкам", 230),
        ("Кладовщик", 170),
        ("Менеджер по продажам", 150)])
    закуп, склад, прод = пул.дорожки

    зазор = пул.y + пул.h + 25            # середина промежутка между пулами
    низ = пул.y + пул.h + 50
    поставщик = м.пул("Поставщик", 0, низ, 910, свернутый=True)
    клиент = м.пул("Клиент", 960, низ, 340, свернутый=True)

    ряд, верх = 45, -60          # основной ряд закупок и ряд артефактов над ним

    старт = м.событие("старт", "Начало недели планирования", закуп, 125,
                      "таймер", dy=ряд)
    учёт = м.данные("Учётная система", закуп, 240, "хранилище", dy=верх,
                    подпись="лево")
    выгрузить = м.задача("Выгрузить остатки и историю продаж", закуп, 240,
                         "пользовательская", dy=ряд)
    определить = м.задача("Определить позиции к пополнению", закуп, 365,
                          "ручная", dy=ряд)
    таблица = м.данные("Таблица расчёта потребности", закуп, 365, dy=верх,
                       подпись="лево")
    нужна = м.шлюз("x", "Пополнение требуется?", закуп, 460, dy=ряд, подпись="низ")
    не_нужна = м.событие("конец", "Закупка не требуется", закуп, 460, "отмена",
                         dy=верх, подпись="право")
    подбор = м.подпроцесс(ПОДБОР, закуп, 587, dy=ряд, w=135, h=105)
    разместить = м.задача("Разместить заказ у поставщика", закуп, 725,
                          "отправка", dy=ряд, w=120)
    заказ = м.данные("Заказ поставщику", закуп, 725, dy=верх, подпись="право")
    прибыла = м.событие("промежуточное", "Поставка прибыла", склад, 830,
                        "сообщение", подпись="верх")
    принять = м.подпроцесс("Принять и оприходовать партию", склад, 935,
                           w=125, h=105)
    отгрузить = м.подпроцесс("Отгрузить товар клиенту", прод, 1075, w=120, h=95)
    закрыт = м.событие("конец", "Товар отгружен, расчёты закрыты", прод, 1185,
                       подпись="право")

    м.поток(старт, выгрузить)
    м.поток(выгрузить, определить)
    м.поток(определить, нужна)
    м.поток(нужна, не_нужна, "Нет", из="верх", в="низ")
    м.поток(нужна, подбор, "Да")
    м.поток(подбор, разместить)
    м.поток(разместить, прибыла, из="право", в="лево")
    м.поток(прибыла, принять)
    м.поток(принять, отгрузить, из="право", в="лево")
    м.поток(отгрузить, закрыт)

    м.данные_в(учёт, выгрузить)
    м.данные_из(определить, таблица)
    м.данные_из(разместить, заказ)

    письмо(м, разместить, поставщик, "Заказ", зазор)
    письмо(м, поставщик, прибыла, "Поставка\nи документы", зазор)
    письмо(м, клиент, отгрузить, "Заявка\nклиента", зазор, x=975, слева=True)
    письмо(м, отгрузить, клиент, "Товар\nи УПД", зазор, x=1110)
    return м


def подбор_as_is() -> Модель:
    """Декомпозиция подпроцесса «Сформировать заказ поставщику»."""
    м = Модель("podbor_as_is", ЗАДАЧА, ШРИФТ)
    ш = 1175
    пул = м.пул(ПОДБОР, 0, 0, ш, [
        ("Менеджер по закупкам", 210),
        ("Руководитель отдела закупок", 240)])
    закуп, рук = пул.дорожки

    зазор = пул.y + пул.h + 25
    поставщик = м.пул("Поставщик", 0, пул.y + пул.h + 50, ш, свернутый=True)
    ряд = 40

    старт = м.событие("старт", "Потребность определена", закуп, 135, dy=ряд)
    запрос = м.задача("Запросить коммерческие предложения", закуп, 250,
                      "отправка", dy=ряд, w=125)
    получены = м.событие("промежуточное", "Предложения получены", закуп, 375,
                         "сообщение", dy=ряд, подпись="верх")
    выбрать = м.задача("Выбрать поставщика по цене", закуп, 495, "ручная",
                       dy=ряд, w=125)
    лимит = м.шлюз("x", "Сумма выше лимита?", закуп, 615, dy=ряд, подпись="верх",
                   подпись_dy=-28)
    согласовать = м.задача("Согласовать закупку", рук, 715, "пользовательская",
                           dy=-50, w=120)
    согласовано = м.шлюз("x", "Согласовано?", рук, 835, dy=-50, подпись="верх")
    отклонён = м.событие("конец", "Заказ отклонён", рук, 835, "отмена", dy=65,
                         подпись="право")
    слияние = м.шлюз("x", "Закупка разрешена", закуп, 945, dy=ряд, подпись="верх")
    сформирован = м.событие("конец", "Заказ сформирован", закуп, 1055, dy=ряд,
                            подпись="право")

    м.поток(старт, запрос)
    м.поток(запрос, получены)
    м.поток(получены, выбрать)
    м.поток(выбрать, лимит)
    м.поток(лимит, согласовать, "Да", из="низ", в="лево")
    м.поток(согласовать, согласовано)
    м.поток(согласовано, отклонён, "Нет", из="низ", в="верх")
    м.поток(согласовано, слияние, "Да", из="право", в="низ")
    м.поток(лимит, слияние, "Нет", из="право", в="лево")
    м.поток(слияние, сформирован)

    письмо(м, запрос, поставщик, "Запрос\nпредложений", зазор)
    письмо(м, поставщик, получены, "Коммерческие\nпредложения", зазор)
    return м


МОДЕЛИ = [("as_is", as_is), ("podbor_as_is", подбор_as_is)]


def артефактов(виды: list[str]) -> int:
    return виды.count("Объект данных") + виды.count("Хранилище данных")


def состав(модели) -> list[str]:
    """Проверки состава по требованиям инструкции к подразделу 2.1."""
    все = [э for _, м in модели for э in м.сводка()]
    виды = [э["вид"] for э in все]
    без_типа = [э["имя"] for э in все
                if э["вид"] == "Задача" and э["тип"] == "Задача без типа"]
    безымянные = [э["вид"] for э in все if not э["имя"]]
    дорожки = {э["дорожка"] for э in все if э["дорожка"]}
    сообщений = sum(len(м.сообщения) for _, м in модели)
    исходы = {э["тип"] for э in все if э["вид"] == "Конечное"}
    проверки = [
        (f"ролей на схемах: {len(дорожки)} ({', '.join(sorted(дорожки))})",
         len(дорожки) >= 4),
        (f"задач без типа: {len(без_типа)}", not без_типа),
        (f"элементов без названия: {len(безымянные)}", not безымянные),
        (f"шлюзов: {виды.count('Шлюз')}", виды.count("Шлюз") >= 3),
        (f"артефактов: {артефактов(виды)}", артефактов(виды) >= 3),
        (f"потоков сообщений: {сообщений}", сообщений >= 4),
        (f"виды конечных событий: {', '.join(sorted(исходы))}", len(исходы) >= 2),
        (f"подпроцесс раскрыт отдельной схемой: {len(модели)} схемы", len(модели) == 2),
    ]
    return ["  " + ("ок  " if ладно else "НЕТ ") + текст for текст, ладно in проверки]


def main() -> int:
    from render_bpmn import рендер, отчёт, ширина_мм

    лог, плохо, собранные = [], 0, []
    for имя, строить in МОДЕЛИ:
        м = строить()
        собранные.append((имя, м))
        файл = м.сохранить(HERE / f"{имя}.bpmn")
        r = рендер(файл, HERE.parent / "img", ШРИФТ)
        лог.append(отчёт(r, ширина_мм(r["w"], r["h"], font=ШРИФТ)))
        for э in м.сводка():
            лог.append("    {вид:<19} | {тип:<24} | {дорожка:<28} | {имя}".format(**э))
        плохо += bool(r["импорт"] or r["линт"] or r["раскладка"])
    лог.append("состав моделей:")
    лог += состав(собранные)
    текст = "\n".join(лог)
    print(текст)
    (HERE.parent / "run.log").write_text(текст + "\n", encoding="utf-8")
    return 1 if плохо else 0


if __name__ == "__main__":
    sys.exit(main())
