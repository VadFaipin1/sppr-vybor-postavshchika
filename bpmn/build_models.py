#!/usr/bin/env python3
"""Модели BPMN к отчёту по учебной практике, вариант 13.

AS-IS, текущее состояние процесса «Закупка, приём и оптовая реализация товаров»:
потребность считается по остатку в выгрузке, поставщик выбирается по цене.

Две схемы. Основная показывает процесс целиком, подбор поставщика свёрнут в
подпроцесс. Декомпозиция раскрывает этот подпроцесс — именно в нём лежат
операции, которые тема работы предлагает автоматизировать.
Одной схемой это не делается: в один ряд получается 1890 px, текст задач
садится до 5 пт при предельной ширине рисунка 250 мм.

Пишет .bpmn, рисунки в ../img и сводку в ../run.log.

    python3 build_models.py
"""
from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ИНСТРУМЕНТ = HERE.parent.parent.parent / "БИЗНЕС ПРОЦЕССЫ" / "Инструменты" / "bpmn"
sys.path.insert(0, str(ИНСТРУМЕНТ))
from bpmn import Модель                                                      # noqa: E402

ШРИФТ = 14
ЗАДАЧА = (130, 104)       # три строки названия не задевают значок типа задачи
ПУЛ_СВЁРНУТЫЙ = 50       # высота свёрнутых пулов Поставщика и Клиента
ПРОЦЕСС = "Закупка, приём и оптовая реализация товаров"
ПОДБОР = "Сформировать заказ поставщику"


def письмо(м: Модель, a, b, имя: str, y: float, x: float | None = None,
           слева: bool = False) -> None:
    """Поток сообщений с подписью в промежутке между пулами.

    Линия сообщения идёт через весь лист, и подпись у её середины легла бы
    на дорожки процесса. y — абсолютная координата середины промежутка."""
    w, h = м._размер_метки(имя)
    ниже = b.y > a.y
    y1 = a.y + a.h if ниже else a.y
    y2 = b.y if ниже else b.y + b.h
    м.сообщение(a, b, имя, x=x,
                подпись=(-6 - w if слева else 6, y - h / 2 - (y1 + y2) / 2))


def as_is() -> Модель:
    """Основная схема AS-IS: от расчёта потребности до отгрузки клиенту.

    Склад и продажи стоят короткой ступенькой под концом ряда закупок, отгрузка —
    прямо под приёмкой, подпись конца процесса — под событием. Так схема на 10 %
    уже прежней, и на листе 250 мм текст задач выходит около 8 пт."""
    м = Модель("as_is", ЗАДАЧА, ШРИФТ)
    ш = 1185
    пул = м.пул(ПРОЦЕСС, 0, 0, ш, [
        ("Менеджер по закупкам", 240),
        ("Кладовщик", 165),
        ("Менеджер по продажам", 160)])
    закуп, склад, прод = пул.дорожки

    зазор = пул.y + пул.h + 25            # середина промежутка между пулами
    низ = пул.y + пул.h + 50
    поставщик = м.пул("Поставщик", 0, низ, 905, свернутый=True, h=ПУЛ_СВЁРНУТЫЙ)
    клиент = м.пул("Клиент", 925, низ, ш - 925, свернутый=True, h=ПУЛ_СВЁРНУТЫЙ)

    ряд, верх = 45, -60          # основной ряд закупок и ряд артефактов над ним

    старт = м.событие("старт", "Начало недели планирования", закуп, 100,
                      "таймер", dy=ряд)
    учёт = м.данные("Учётная система", закуп, 215, "хранилище", dy=верх,
                    подпись="лево")
    выгрузить = м.задача("Выгрузить остатки и историю продаж", закуп, 215,
                         "пользовательская", dy=ряд)
    определить = м.задача("Определить позиции к пополнению", закуп, 370,
                          "ручная", dy=ряд)
    таблица = м.данные("Таблица расчёта потребности", закуп, 370, dy=верх,
                       подпись="лево")
    нужна = м.шлюз("x", "Пополнение требуется?", закуп, 480, dy=ряд, подпись="низ")
    не_нужна = м.событие("конец", "Закупка не требуется", закуп, 480, "отмена",
                         dy=верх, подпись="право")
    подбор = м.подпроцесс(ПОДБОР, закуп, 603, dy=ряд, w=135)
    разместить = м.задача("Разместить заказ у поставщика", закуп, 755,
                          "отправка", dy=ряд)
    заказ = м.данные("Заказ поставщику", закуп, 755, dy=верх, подпись="право")
    прибыла = м.событие("промежуточное", "Поставка прибыла", склад, 870,
                        "сообщение", подпись="верх", подпись_dx=12)
    принять = м.подпроцесс("Принять и оприходовать партию", склад, 990)
    отгрузить = м.подпроцесс("Отгрузить товар клиенту", прод, 990, dy=-10, h=95)
    закрыт = м.событие("конец", "Товар отгружен, расчёты закрыты", прод, 1110,
                       dy=-10, подпись="низ")

    м.поток(старт, выгрузить)
    м.поток(выгрузить, определить)
    м.поток(определить, нужна)
    м.поток(нужна, не_нужна, "Нет", из="верх", в="низ")
    м.поток(нужна, подбор, "Да")
    м.поток(подбор, разместить)
    м.поток(разместить, прибыла, из="право", в="лево")
    м.поток(прибыла, принять)
    м.поток(принять, отгрузить, из="низ", в="верх")
    м.поток(отгрузить, закрыт)

    м.данные_в(учёт, выгрузить)
    м.данные_из(определить, таблица)
    м.данные_из(разместить, заказ)

    письмо(м, разместить, поставщик, "Заказ", зазор, x=720, слева=True)
    письмо(м, поставщик, прибыла, "Поставка\nи документы", зазор, слева=True)
    письмо(м, клиент, отгрузить, "Заявка\nклиента", зазор, x=955, слева=True)
    письмо(м, отгрузить, клиент, "Товар\nи УПД", зазор, x=1030)
    return м


def подбор_as_is() -> Модель:
    """Декомпозиция подпроцесса «Сформировать заказ поставщику»."""
    м = Модель("podbor_as_is", ЗАДАЧА, ШРИФТ)
    ш = 1175
    пул = м.пул(ПОДБОР, 0, 0, ш, [
        ("Менеджер по закупкам", 210),
        ("Руководитель отдела закупок", 240)])
    закуп, рук = пул.дорожки

    зазор = пул.y + пул.h + 25
    поставщик = м.пул("Поставщик", 0, пул.y + пул.h + 50, ш, свернутый=True,
                      h=ПУЛ_СВЁРНУТЫЙ)
    ряд = 40

    старт = м.событие("старт", "Потребность определена", закуп, 120, dy=ряд)
    запрос = м.задача("Запросить коммерческие предложения", закуп, 240,
                      "отправка", dy=ряд)
    получены = м.событие("промежуточное", "Предложения получены", закуп, 365,
                         "сообщение", dy=ряд, подпись="верх")
    выбрать = м.задача("Выбрать поставщика по цене", закуп, 490, "ручная", dy=ряд)
    лимит = м.шлюз("x", "Сумма выше лимита?", закуп, 610, dy=ряд, подпись="верх",
                   подпись_dy=-28)
    согласовать = м.задача("Согласовать закупку", рук, 720, "пользовательская",
                           dy=-50)
    согласовано = м.шлюз("x", "Согласовано?", рук, 845, dy=-50, подпись="верх")
    отклонён = м.событие("конец", "Заказ отклонён", рук, 845, "отмена", dy=65,
                         подпись="право")
    слияние = м.шлюз("x", "Закупка разрешена", закуп, 955, dy=ряд, подпись="верх")
    сформирован = м.событие("конец", "Заказ сформирован", закуп, 1055, dy=ряд,
                            подпись="право")

    м.поток(старт, запрос)
    м.поток(запрос, получены)
    м.поток(получены, выбрать)
    м.поток(выбрать, лимит)
    м.поток(лимит, согласовать, "Да", из="низ", в="лево")
    м.поток(согласовать, согласовано)
    м.поток(согласовано, отклонён, "Нет", из="низ", в="верх")
    м.поток(согласовано, слияние, "Да", из="право", в="низ")
    м.поток(лимит, слияние, "Нет", из="право", в="лево")
    м.поток(слияние, сформирован)

    письмо(м, запрос, поставщик, "Запрос\nпредложений", зазор)
    письмо(м, поставщик, получены, "Коммерческие\nпредложения", зазор)
    return м


def to_be() -> Модель:
    """Процесс после внедрения: расчёт и рейтинг делает система, менеджер проверяет.

    Как и в AS-IS, отгрузка стоит под фиксацией факта, а не ещё одной ступенькой
    правее, а хранилище для факта — справа от задачи: схема уже и ниже, и на
    листе 250 мм текст задач около 8 пт."""
    м = Модель("to_be", ЗАДАЧА, ШРИФТ)
    ш = 1185
    пул = м.пул(ПРОЦЕСС, 0, 0, ш, [
        ("Система поддержки решений", 190),
        ("Менеджер по закупкам", 130),
        ("Кладовщик", 150),
        ("Менеджер по продажам", 158)])
    сппр, закуп, склад, прод = пул.дорожки

    зазор = пул.y + пул.h + 25
    низ = пул.y + пул.h + 50
    поставщик = м.пул("Поставщик", 0, низ, 905, свернутый=True, h=ПУЛ_СВЁРНУТЫЙ)
    клиент = м.пул("Клиент", 925, низ, ш - 925, свернутый=True, h=ПУЛ_СВЁРНУТЫЙ)

