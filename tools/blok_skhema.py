#!/usr/bin/env python3
"""Блок-схема алгоритма расчёта проекта заказа (фигуры по ГОСТ 19.701-90).

Терминатор — скруглённый прямоугольник, процесс — прямоугольник, решение —
ромб, данные — параллелограмм. Пишет ../img/algoritm.png.

    python3 tools/blok_skhema.py
"""
from __future__ import annotations

import struct
import subprocess
from pathlib import Path

BASE = Path(__file__).resolve().parent.parent
ШРИФТ = "Times New Roman"

УЗЛЫ = [
    ("начало", "терм", "Начало"),
    ("ввод", "данные", "Параметры расчёта,\nдата расчёта"),
    ("веса", "процесс", "Веса критериев\nметодом анализа иерархий"),
    ("ос", "решение", "ОС < 0,1?"),
    ("отказ", "данные", "Сообщение\nо несогласованности"),
    ("данные", "данные", "Продажи, остатки, прайсы,\nисполнение поставок"),
    ("классы", "процесс", "Классы ABC и XYZ"),
    ("рейтинг", "процесс", "Баллы поставщиков\nпо всем позициям"),
    ("цикл", "решение", "Есть ещё\nпозиция?"),
    ("лучший", "процесс", "Лучший поставщик позиции,\nего срок поставки"),
    ("тп", "процесс", "Точка перезаказа\nпо уровню обслуживания класса"),
    ("нужно", "решение", "Доступно ≤\nточки перезаказа?"),
    ("партия", "процесс", "Экономичная партия,\nпотолок по сроку годности,\nкратность упаковки"),
    ("строка", "процесс", "Строка проекта заказа"),
    ("минимум", "процесс", "Сверка с минимальной\nсуммой заказа"),
    ("вывод", "данные", "Проект заказа, рейтинг,\nсостояние; оценки в базу"),
    ("конец", "терм", "Конец"),
]

СВЯЗИ = [
    ("начало", "ввод", ""), ("ввод", "веса", ""), ("веса", "ос", ""),
    ("ос", "отказ", "нет"), ("отказ", "конец", ""),
    ("ос", "данные", "да"), ("данные", "классы", ""), ("классы", "рейтинг", ""),
    ("рейтинг", "цикл", ""), ("цикл", "лучший", "да"), ("лучший", "тп", ""),
    ("тп", "нужно", ""), ("нужно", "партия", "да"), ("нужно", "цикл", "нет"),
    ("партия", "строка", ""), ("строка", "цикл", ""),
    ("цикл", "минимум", "нет"), ("минимум", "вывод", ""), ("вывод", "конец", ""),
]

ФИГУРЫ = {
    "терм": 'shape=box, style="rounded,filled", fillcolor="#f2f2f2"',
    "процесс": 'shape=box, style=filled, fillcolor="#dbe5f1"',
    "решение": 'shape=diamond, style=filled, fillcolor="#fdebd0"',
    # параллелограмм graphviz скошен сильно и раздувает схему вширь
    "данные": 'shape=polygon, sides=4, skew=0.18, style=filled, fillcolor="#e8f0e0"',
}


def main() -> None:
    с = ["digraph A {",
         f'  graph [rankdir=TB, nodesep=0.35, ranksep=0.28, fontname="{ШРИФТ}"];',
         f'  node [fontname="{ШРИФТ}", fontsize=12, margin="0.12,0.05"];',
         f'  edge [fontname="{ШРИФТ}", fontsize=11, arrowsize=0.7];']
    for ид, вид, текст in УЗЛЫ:
        с.append(f'  "{ид}" [{ФИГУРЫ[вид]}, label="{текст}"];')
    for a, b, подпись in СВЯЗИ:
        # подпись ветви у выхода из ромба, а не посреди линии
        доп = (f', taillabel="{подпись}", labeldistance=1.6, labelangle=-35'
               if подпись else "")
        if (a, b) in (("нужно", "цикл"), ("строка", "цикл")):
            доп += ", constraint=false"
        с.append(f'  "{a}" -> "{b}" [{доп.lstrip(", ")}];')
    с.append("}")
    файл = BASE / "tools" / "algoritm.dot"
    файл.write_text("\n".join(с) + "\n", encoding="utf-8")
    png = BASE / "img" / "algoritm.png"
    subprocess.run(["dot", "-Tpng", "-Gdpi=150", str(файл), "-o", str(png)], check=True)
    w, h = struct.unpack(">II", png.read_bytes()[16:24])
    мм = w / 150 * 25.4
    print(f"algoritm.png: {w}x{h} px, натуральная ширина {мм:.0f} мм, "
          f"при ширине 160 мм кегль {12 * min(1, 160 / мм):.1f} пт, высота {min(160, мм) * h / w:.0f} мм")


if __name__ == "__main__":
    main()
